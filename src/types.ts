// All on-chain numbers are decimal strings of integers (bigint-safe), never JS numbers.

import type { FalseAlarmRow, PassRuleLine } from "./falsealarm";
import type { OutlineSection } from "./outline/types";
import type { RunCondition } from "./conditions";
export type TargetKind = "ts-fixture" | "github-pr" | "pasted";
export interface Target {
  kind: TargetKind;
  /** ts-fixture: path inside tests/fixtures; github-pr: owner/repo#number; pasted: "pasted:<first 12 hex of codeSha256>" */
  ref: string;
  /** SHA-256 of the exact bytes Atlas read (file, or the concatenated PR files in path order). */
  codeSha256: string;
  /** github-pr only: merge commit the files were fetched at. */
  commit?: string;
  /** Label shown on screen when the target predates Oct 27 (PRE-EXISTING.md). */
  preExisting?: { label: string; listedIn: "PRE-EXISTING.md" };
  /** Added E1 (any-code spec): pasted only. The language of the pasted file. */
  language?: "js" | "ts" | "py";
  /** Added E1: pasted only. The pasted file itself (one file, at most 64 KB), so a run can be replayed and verified. */
  source?: string;
}

export type FindingKind = "retry" | "price" | "other";
export interface Finding {
  id: string;
  file: string;              // path as in the target
  lineStart: number;         // 1-based, inclusive
  lineEnd: number;           // 1-based, inclusive, >= lineStart
  kind: FindingKind;
  /** The model's sentence about what people likely expect vs what the code does. Shown in the model panel only; never in a verdict. */
  claim: string;
  /** True only after plain code confirmed file exists, lines exist, and the quoted snippet matches the file bytes. */
  verified: boolean;
  /** The exact text the model quoted; verification compares it (whitespace-normalised) to the file. */
  quotedSnippet: string;
  /** Changed D04-04: a person may pick the lines themselves (role "human", no model); their finding has an empty claim. */
  proposedBy: { role: "investigator"; model: string } | { role: "human"; model: "none: picked by a person" };   // e.g. "muse-wonder-1.0"
}

export type BetAnswer =
  | { kind: "integer"; value: number }                                   // exact match
  | { kind: "number"; value: number; tolerancePct: number; unit: string } // |run - value| <= tolerancePct% of run
  | { kind: "enum"; value: string; options: string[] }                   // exact match
  | { kind: "json"; value: JsonValue }                                   // Added E1: canonical-JSON equality (returnedJson)
  /** Added U1 (D48): one tap on a quiz question. `options` are the question's own options (src/quiz.ts), sealed with the bet. */
  | { kind: "quiz"; choice: string; options: QuizOption[] }              // matched when the measured value is inside the chosen option
  | { kind: "declined"; reason: string };                                // the bettor would not guess → verdict "cant_check"

/**
 * Added U1 (D48): what one quiz option covers. Plain code (src/quiz.ts) writes every option from the test itself, never
 * from a run. "word": the measured word equals `value`. "count": a whole number from min to max (both included; max null
 * = no upper end). "ms": a time range; `minOpen` / `maxOpen` leave that end out. "json": exactly this value (canonical
 * JSON). "json-other": any JSON value that is none of `not`.
 */
export type QuizMatch =
  | { kind: "word"; value: string }
  | { kind: "count"; min: number; max: number | null }
  | { kind: "ms"; min: number; max: number | null; minOpen: boolean; maxOpen: boolean }
  | { kind: "json"; value: JsonValue }
  | { kind: "json-other"; not: JsonValue[] };
export interface QuizOption {
  /** "a", "b", "c", ... in the order shown. */
  id: string;
  /** The words on the option, written by plain code. */
  label: string;
  match: QuizMatch;
}

export interface Bet {
  id: string;
  experimentId: string;
  who: "human" | `model:${string}`;        // "model:muse-spark-1.3", "model:meta-models/muse-spark-open-1026"
  /** The question is generated by plain code from the experiment shape, never by a model. */
  question: string;
  /** Which measured field of RunResult this bet is about. The judge reads only this field. */
  measures: string;                         // e.g. "calls", "totalWaitMs", "outcome", "priceUsd1e18:cbETH"
  answer: BetAnswer;
  nonce: string;                            // 16 random bytes hex; makes the hash unguessable
  sealedAt: string;
  /** sha256(canonicalJson({who, experimentId, question, measures, answer, nonce, sealedAt, rationale?})). Shown on screen BEFORE the run. */
  sealedHash: string;
  /** Model bets only: what the model said; shown in the model panel. Sealed with the bet when present. */
  rationale?: string;
  /**
   * Added E3 review r2 (M2): the round repeats a test already run in this session, so the person may know its result.
   * Sealed with the bet. A track record (X3) can leave these bets out.
   */
  repeat?: true;
}

/** A plain JSON value (what a fake RPC call may resolve with). */
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

export type ExperimentShape =
  // TS runner
  | {
      shape: "retry-scenario"; failTimes: number | "always"; failure: "error" | "never_settles"; attempts?: number; delayMs?: number; resolveAfterMs?: number;
      /** Added D01-08 (oracle row S4). How a failing call fails: "seeded" (default) = an error picked by the seed; "429" = an HTTP 429 error every time. */
      errorKind?: "seeded" | "429";
      /** Added D01-08 (oracle row S5). What a successful call resolves with. Default: the string "the value". */
      resolvesWith?: JsonValue;
    }
  | { shape: "concurrency-sweep"; callers: number; failTimes: number | "always"; failure: "error"; delayMs?: number }  // callers 1..200
  // Added E1 (any-code spec): call one exported function of a pasted file with JSON args and stand-ins.
  | {
      shape: "call-function";
      /** An exported function of the pasted file, found by plain code (src/pasted-code.ts). */
      exportName: string;
      /** At most 8. The JSON values in them total at most 4 KB as canonical JSON. */
      args: ArgSpec[];
      /** Atlas's watch limit in VIRTUAL ms. Default 30_000, at most 600_000. */
      watchLimitMs?: number;
      /**
       * U2 (D53): a scripted fake for the network library the code calls (global fetch in JS/TS; requests, urllib.request
       * or httpx in Python), installed in the sandbox in place of that library. The network itself stays blocked. Its
       * calls are counted like a stand-in's, as `calls:<replaces>`.
       */
      network?: NetworkFake;
    }
  // EVM runner
  | { shape: "price-read"; markets: string[] }                                   // read getUnderlyingPrice at the fork block
  | { shape: "apply-proposal-then-read"; markets: string[] | "touched" }         // Level 2
  | { shape: "liquidatable-at-price"; market: string; priceUsd1e18: string };    // cut first if time slips

/**
 * Added E1: one argument of a "call-function" experiment. A stand-in is a fake function passed as an argument
 * (the general form of retry-scenario's fake RPC). Its name is for display only.
 */
export type ArgSpec =
  | { kind: "json"; value: JsonValue }
  | {
      kind: "stand-in";
      name: string;
      async: boolean;
      /** 1..50 steps, used in call order. */
      calls: StandInStep[];
      /** After the last step: do the last step again, or throw (AtlasStandInExhausted). */
      then: "repeat_last" | "throw_exhausted";
    };
/** U2 (D53): the network library a fake replaces. */
export type NetworkLibrary = "fetch" | "requests" | "urllib" | "httpx";
/** U2 (D53): a scripted fake network. Same contract as a stand-in: steps in call order, then repeat_last or throw_exhausted. */
export interface NetworkFake {
  replaces: NetworkLibrary;
  /** 1..50 steps, used in call order. */
  calls: NetworkStep[];
  then: "repeat_last" | "throw_exhausted";
}
/**
 * U2 (D53): what the fake network does on one call. "respond": an HTTP answer with this status and this JSON body
 * (after `afterMs` virtual ms); "throw": a named network error (the library's own class of that name); "never_answer":
 * no answer at all (only the code's own timeout or abort, if it set one, ends the wait).
 */
export type NetworkStep =
  | { do: "respond"; status: number; body: JsonValue; afterMs?: number }
  | { do: "throw"; errorName: string; message: string }
  | { do: "never_answer" };

/** What a stand-in does on one call. afterMs (virtual) and never_settle are for async stand-ins only. */
export type StandInStep =
  | { do: "return"; value: JsonValue; afterMs?: number }
  | { do: "throw"; errorName: string; message: string }
  | { do: "never_settle" };

export interface Experiment {
  id: string;
  target: Target;
  runner: "ts" | "evm";
  params: ExperimentShape;
  /** Added E3: "investigator" = Muse Wonder proposed this call-function test for pasted code. */
  proposedBy: {
    role: "claimant" | "adversary" | "human" | "investigator";
    model?: string;
    /** Added E3 review (D10): a person's test edited from a model's proposal names that model and proposal too. */
    editedFrom?: { model: string; proposalId: string };
  };
  /** Set by src/gate.ts. A rejected experiment is kept (and shown in the log strip) but never run. */
  gate: { allowed: true } | { allowed: false; reason: string };
}

export interface TraceEvent { t: number; event: string; data?: Record<string, unknown> }  // t = virtual ms (ts) or call index (evm)

export interface RunResult {
  /** Every field here was MEASURED by the runner. A field absent = not measured = "cant_check". */
  measured: Record<string, string | number | boolean | null>;
  /**
   * Fields the runner knows it did NOT measure, with why (shown as "can't check: <why>").
   * Added E1: the key `wholeRun` means nothing in the run counts (the code needs a package, the sandbox refused
   * an access, the export is missing, ...). Every verdict on such a run is "cant_check" with that reason.
   */
  notMeasured: Record<string, string>;
  /** EVM: independent references computed by plain code at the same block, e.g. "refUsd1e18:cbETH". */
  references?: Record<string, { value: string; method: string }>;
}

export interface Run {
  id: string;
  experimentId: string;
  runner: "ts" | "evm";
  executor: "local" | "modal";
  codeSha256: string;
  forkBlock?: number;        // evm
  chainId?: number;          // evm, 8453
  seed?: string;             // ts: seeds the fake RPC's error choice; call-function (R1): seeds all the code's randomness; same seed = same run
  /** R1 (D42): the time zone a call-function run was pinned to ("UTC"). Absent on older files and other runs. */
  timeZone?: string;
  /** R1 (D42): the locale a call-function run was pinned to ("en-US" for JavaScript, "C" for Python). */
  locale?: string;
  /** R1 (D42): what the result depends on that is Atlas's, not the code's (src/conditions.ts). The "conditions" line. */
  conditions?: RunCondition[];
  /**
   * R1 review round 1: the second, identical run of a pasted test (fresh sandbox, same seed and pins). A field it
   * measured differently is not reported in `result`; verify rechecks this against it (src/conditions.ts).
   */
  twin?: { trace: TraceEvent[]; result: RunResult };
  startedAt: string; finishedAt: string;
  trace: TraceEvent[];
  result: RunResult;
  /** The harness ran its known-true control first and it matched. If false, every verdict on this run is "cant_check". */
  controlPassed: boolean;
  controlRunId?: string;
  /** Present when this run is the replay after a change (step 9). */
  replayOf?: { runId: string; changeId: string };
}

export type Outcome = "matched" | "not_matched" | "cant_check";
export interface Verdict {
  betId: string;
  runId: string;
  outcome: Outcome;
  /** The measured value the bet was judged against, as the runner stored it. */
  observed?: string | number | boolean | null;
  reference?: { value: string; method: string };
  /** Only for cant_check: the plain-code reason (control failed / field not measured / bet declined). */
  reason?: string;
  judgedBy: "src/judge.ts";  // literal; the UI prints it
  /**
   * R2 (D46): the timing rule this verdict was judged with, on a matched / not matched number bet in ms: "d46" =
   * within tolerancePct% OR within 1 ms. Absent = the rule before D46 (tolerancePct% only); verify re-judges with it.
   */
  timingRule?: "d46";
}

export interface Change {
  id: string;
  runId: string;
  /** Unified diff proposed by the Fixer. Applied in a scratch copy only. */
  diff: string;
  /** D07-04: `path` says which Fixer path ran ("muse-exec" = Muse Code, "chat-fallback" = Muse Spark chat). Older files have none. */
  proposedBy: { role: "fixer"; model: string; path?: "muse-exec" | "chat-fallback" };
  /** What the bettors expected; the change is "toward" this, never "a fix". */
  toward: string;
  replayRunId?: string;
  /**
   * D20: present only when the change could be wired solely by connecting a feed directly (no
   * "<name>_OEV_WRAPPER" in the PR's address book, "<name>" present). Every screen says "In theory".
   */
  mode?: "theoretical-direct-wire";
  /** D20: the feeds wired directly: the config's oracle name, the market, and the address-book address used. */
  directWired?: { oracleName: string; market: string; address: string }[];
}

export interface AgentEvent {   // one line of the on-screen agent log
  t: string;                    // ISO time
  role: "investigator" | "claimant" | "gate" | "runner" | "judge" | "fixer" | "adversary" | "seal" | "human";
  model?: string;               // Meta model id, always shown on screen when a model acted
  action: string;               // short, present tense: "reads 6 files (31,204 tokens)", "proposes retry-scenario", "allowed", "forks Base @ 42194662"
  /** "target": final review M3, the code a model read (id = its codeSha256), so a round can tell whether the Investigator read ITS code. */
  ref?: { kind: "finding" | "experiment" | "bet" | "run" | "verdict" | "change" | "target"; id: string };
  usage?: { promptTokens: number; completionTokens: number; reasoningTokens?: number; usd: number };
}

/**
 * Day-7 review M3/M7: who was asked to bet in the round, and how each answered. "sealed": it has bets in the
 * file. "no_usable_answer": a model was asked but sealed nothing (e.g. a network error): NOT a decline.
 * "not_asked": the person in an autonomous round, or a model the server did not ask. `reason` is plain code's.
 */
export interface BettorSlot {
  who: "human" | `model:${string}`;
  status: "sealed" | "no_usable_answer" | "not_asked";
  reason?: string;
}

/**
 * Final review S2: a run attempt that did not finish (no RPC, anvil failed, the sandbox could not start). The
 * experiment and its sealed bets stay as they were and the same experiment can run again. An attempt is never
 * a verdict: it has no measurement and judges nothing. `reason` is plain code's, with the RPC URL removed.
 */
export interface RunAttempt {
  attempt: number;
  /** When the bets were frozen for this attempt (server clock). */
  startedAt: string;
  stoppedAt: string;
  reason: string;
}

/**
 * R2 review round 1 (B1, B2): the rules a proof file was made under, written by buildAtlasFile and checked by verify.
 * timing "d46": timing bets judged within 10% or 1 ms; conditions "r2": D45's timed-work words and second run.
 * A file without it was made before R2 and is judged by the rules before R2.
 */
export interface AtlasRules {
  timing: "d46";
  conditions: "r2";
  /** U2 (D53): timing options of a call still running at the watch limit are judged as "more than the limit". */
  watchLimit?: "u2";
}

export interface AtlasFile {
  version: 1;
  rules?: AtlasRules;
  target: Target;
  codeSha256: string;
  forkBlock?: number; chainId?: number; seed?: string;
  experiments: Experiment[];
  bets: Bet[];
  runs: Run[];
  verdicts: Verdict[];
  change?: Change;
  /**
   * D06-01: the replay after `change`: the SAME experiment on the changed code (same seed / same fork
   * block), the SAME bets judged against it, and on Moonwell the PASS-RULE.md replay lines.
   * Verify recomputes all of it (src/atlasfile.ts changeProblems).
   */
  replay?: { run: Run; verdicts: Verdict[]; passRule?: PassRuleLine[] };
  /** Added D04-04: the finding the round worked on (findings[0]), with who proposed it. Since M7 the rest are the
   *  Investigator's verified places on the same code, so the "pointed elsewhere / also pointed here" caption can be rechecked. */
  findings?: Finding[];
  /** Level 2 only: the false-alarm table, rebuilt from the run by src/falsealarm.ts (verify recomputes it). */
  falseAlarm?: FalseAlarmRow[];
  agentLog: AgentEvent[];
  /** Added day-7 review: every bettor of the round, including those who sealed nothing. Older files have none. */
  bettors?: BettorSlot[];
  /** Added final review S2: earlier attempts of this experiment that did not finish, oldest first. Older files have none. */
  attempts?: RunAttempt[];
  /** Text a replayer must show: pre-existing labels, "replayed on a fork", "mechanism, not an incident". */
  captions: string[];
  /**
   * Added X1: the code explorer's outline (source files + hashes, code map, Wonder's outline, plain code's verified
   * outline, usage). Verify rebuilds the code map and the verification from the stored files, without any model.
   */
  outline?: OutlineSection;
  createdAt: string;
}
