// R3: writes renderer/metrics.ts, the width of every character of the self-hosted font, read from the font file itself.
// Plain words: the browser and Node must agree on how wide a word is, or the same spec lays out differently in each.
// So widths come from one table, and the drawing turns kerning off, so the browser draws exactly those widths.
//   node renderer/tools/build-metrics.mjs   (needs the dev dependency @napi-rs/canvas; only re-run if the font changes)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createCanvas, GlobalFonts } from "@napi-rs/canvas";

const here = import.meta.dirname;
const fonts = { regular: "besley-latin-400-normal.woff2", italic: "besley-latin-400-italic.woff2" };
const out = {};
for (const [name, file] of Object.entries(fonts)) {
  const family = `R3-${name}`;
  if (!GlobalFonts.registerFromPath(join(here, "..", "fonts", file), family)) throw new Error(`could not load ${file}`);
  const g = createCanvas(8, 8).getContext("2d");
  g.font = `1000px "${family}"`;
  const widths = {};
  // The latin subset's characters, per the subset's unicode range.
  const ranges = [[0x20, 0x7e], [0xa0, 0xff], [0x131, 0x131], [0x152, 0x153], [0x2c6, 0x2c6], [0x2da, 0x2da], [0x2dc, 0x2dc], [0x2010, 0x2027], [0x2030, 0x205e], [0x20ac, 0x20ac], [0x2122, 0x2122], [0x2191, 0x2191], [0x2193, 0x2193], [0x2212, 0x2212], [0x2215, 0x2215]];
  for (const [a, b] of ranges) for (let c = a; c <= b; c++) widths[String.fromCodePoint(c)] = Math.round(g.measureText(String.fromCodePoint(c)).width);
  out[name] = widths;
}
const body = `// Generated by renderer/tools/build-metrics.mjs from renderer/fonts (Besley, SIL OFL 1.1). Width per character, per 1000 px of font size.\nexport const METRICS: Record<"regular" | "italic", Record<string, number>> = ${JSON.stringify(out)};\n`;
writeFileSync(join(here, "..", "metrics.ts"), body);
console.log("metrics", Object.keys(out.regular).length, "a=", out.regular.a, "i-a=", out.italic.a, "W=", out.regular.W);
